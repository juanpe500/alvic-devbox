"""Alvic devbox agent — the phone's remote hands inside the devbox container.

Bound to 127.0.0.1 and reached only through `tailscale serve` (tailnet HTTPS).
Every route requires the bearer token generated by install.sh.

Surface:
  GET  /health                     box info
  GET  /fs/list | /fs/read | /fs/search
  POST /fs/write | /fs/mkdir | /fs/move | /fs/delete
  POST /exec                       one-shot command (≤ 15 min)
  POST /jobs, GET /jobs, GET /jobs/{id}, POST /jobs/{id}/stop   long-running processes
  GET  /ports                      listening TCP ports (for previews)
  *    /proxy/{port}/{path}        HTTP proxy to 127.0.0.1:{port} — previews never leave the tailnet
  WS   /pty                        interactive terminal, attached to a tmux session so it
                                   survives the phone disconnecting
"""

from __future__ import annotations

import asyncio
import fcntl
import hmac
import json
import os
import shutil
import signal
import socket
import struct
import subprocess
import termios
import time
import uuid
from pathlib import Path

import httpx
from fastapi import FastAPI, HTTPException, Request, WebSocket, WebSocketDisconnect
from fastapi.responses import JSONResponse, Response

VERSION = "1"
HOME = Path(os.environ.get("HOME", "/home/dev")).resolve()
TOKEN = os.environ.get("AGENT_TOKEN", "")
STATE_DIR = HOME / ".devbox"
JOBS_DIR = STATE_DIR / "jobs"
JOBS_DIR.mkdir(parents=True, exist_ok=True)

READ_MAX = 400_000
OUTPUT_MAX = 100_000
LIST_MAX = 2000
EXEC_MAX_TIMEOUT = 900

app = FastAPI(title="alvic-devbox", version=VERSION, docs_url=None, redoc_url=None)


# ── auth ────────────────────────────────────────────────────────────────────

def _token_ok(raw: str | None) -> bool:
    return bool(TOKEN) and bool(raw) and hmac.compare_digest(raw, TOKEN)


def _bearer(value: str | None) -> str | None:
    if value and value.lower().startswith("bearer "):
        return value[7:].strip()
    return None


@app.middleware("http")
async def require_token(request: Request, call_next):
    raw = _bearer(request.headers.get("authorization")) or request.query_params.get("token")
    if not _token_ok(raw):
        return JSONResponse({"error": "unauthorized"}, status_code=401)
    return await call_next(request)


# ── helpers ─────────────────────────────────────────────────────────────────

def _safe(path: str | None) -> Path:
    """Resolve a path (relative to $HOME, or absolute inside it). Never escapes $HOME."""
    raw = (path or "").strip()
    target = Path(raw) if raw.startswith("/") else HOME / raw
    target = target.resolve()
    if target != HOME and HOME not in target.parents:
        raise HTTPException(400, "path escapes the home folder")
    return target


def _rel(p: Path) -> str:
    return "" if p == HOME else str(p.relative_to(HOME))


def _head_tail(text: str, limit: int = OUTPUT_MAX) -> str:
    if len(text) <= limit:
        return text
    head, tail = text[: int(limit * 0.6)], text[-int(limit * 0.4):]
    return f"{head}\n\n… [{len(text) - len(head) - len(tail):,} chars omitted] …\n\n{tail}"


def _child_env(extra: dict | None = None) -> dict:
    env = {k: v for k, v in os.environ.items() if k != "AGENT_TOKEN"}
    env.setdefault("TERM", "xterm-256color")
    env["HOME"] = str(HOME)
    if extra:
        env.update(extra)
    return env


def _kill_group(proc: subprocess.Popen | asyncio.subprocess.Process, sig=signal.SIGTERM) -> None:
    try:
        os.killpg(proc.pid, sig)
    except (ProcessLookupError, PermissionError):
        pass


# ── info ────────────────────────────────────────────────────────────────────

@app.get("/health")
def health():
    try:
        mem_limit = int(Path("/sys/fs/cgroup/memory.max").read_text().strip())
    except (OSError, ValueError):
        mem_limit = None
    try:
        quota, period = Path("/sys/fs/cgroup/cpu.max").read_text().split()
        cpus = None if quota == "max" else round(int(quota) / int(period), 2)
    except (OSError, ValueError):
        cpus = None
    return {
        "ok": True,
        "version": VERSION,
        "hostname": socket.gethostname(),
        "home": str(HOME),
        "cpus": cpus,
        "memory_bytes": mem_limit,
        "claude": shutil.which("claude", path=_child_env()["PATH"]) is not None,
    }


# ── files ───────────────────────────────────────────────────────────────────

@app.get("/fs/list")
def fs_list(path: str = "", hidden: bool = False):
    base = _safe(path)
    if not base.exists():
        raise HTTPException(404, f"not found: {path}")
    if not base.is_dir():
        raise HTTPException(400, f"not a folder: {path}")
    entries = []
    for child in sorted(base.iterdir(), key=lambda c: (not c.is_dir(), c.name.lower())):
        if not hidden and child.name.startswith("."):
            continue
        try:
            st = child.stat()
        except OSError:
            continue
        entries.append({
            "name": child.name,
            "path": _rel(child),
            "dir": child.is_dir(),
            "size": st.st_size,
            "mtime": int(st.st_mtime),
        })
        if len(entries) >= LIST_MAX:
            break
    is_repo = (base / ".git").exists()
    return {"path": _rel(base), "entries": entries, "git": is_repo}


@app.get("/fs/read")
def fs_read(path: str):
    target = _safe(path)
    if not target.is_file():
        raise HTTPException(404, f"not a file: {path}")
    size = target.stat().st_size
    with open(target, "rb") as fh:
        data = fh.read(READ_MAX)
    if b"\x00" in data[:8000]:
        raise HTTPException(415, "binary file")
    return {
        "path": _rel(target),
        "content": data.decode("utf-8", errors="replace"),
        "size": size,
        "truncated": size > READ_MAX,
    }


@app.post("/fs/write")
async def fs_write(request: Request):
    body = await request.json()
    target = _safe(body.get("path"))
    if target == HOME:
        raise HTTPException(400, "path required")
    target.parent.mkdir(parents=True, exist_ok=True)
    content = body.get("content") or ""
    target.write_text(content, encoding="utf-8")
    return {"ok": True, "path": _rel(target), "chars": len(content)}


@app.post("/fs/mkdir")
async def fs_mkdir(request: Request):
    body = await request.json()
    target = _safe(body.get("path"))
    target.mkdir(parents=True, exist_ok=True)
    return {"ok": True, "path": _rel(target)}


@app.post("/fs/move")
async def fs_move(request: Request):
    body = await request.json()
    src, dst = _safe(body.get("src")), _safe(body.get("dst"))
    if src == HOME:
        raise HTTPException(400, "refusing to move the home folder")
    if not src.exists():
        raise HTTPException(404, "source not found")
    if dst.exists():
        raise HTTPException(409, "destination exists")
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.move(str(src), str(dst))
    return {"ok": True, "src": _rel(src), "dst": _rel(dst)}


@app.post("/fs/delete")
async def fs_delete(request: Request):
    """Deleting a non-empty folder needs recursive=true; the phone only sends that
    after the user explicitly confirms."""
    body = await request.json()
    target = _safe(body.get("path"))
    if target == HOME:
        raise HTTPException(400, "refusing to delete the home folder")
    if not target.exists():
        raise HTTPException(404, "not found")
    if target.is_dir() and not target.is_symlink():
        count = sum(1 for _ in target.rglob("*"))
        if count and not body.get("recursive"):
            return JSONResponse({"error": "not_empty", "count": count}, status_code=409)
        shutil.rmtree(target)
    else:
        target.unlink()
    return {"ok": True, "path": _rel(target)}


@app.get("/fs/search")
def fs_search(q: str, path: str = "", regex: bool = False, glob: str = ""):
    base = _safe(path)
    if shutil.which("rg"):
        cmd = ["rg", "--line-number", "--no-heading", "--color=never", "--max-count=50",
               "--max-columns=300", "-S"]
        if not regex:
            cmd.append("-F")
        if glob:
            cmd += ["-g", glob]
    else:
        cmd = ["grep", "-rnI", "-i", "--exclude-dir=.git", "--exclude-dir=node_modules"]
        cmd.append("-F" if not regex else "-E")
        if glob:
            cmd.append(f"--include={glob}")
    cmd += ["--", q, str(base)]
    try:
        out = subprocess.run(cmd, capture_output=True, text=True, timeout=60).stdout
    except subprocess.TimeoutExpired:
        raise HTTPException(504, "search timed out")
    prefix = str(HOME) + "/"
    lines = [ln[len(prefix):] if ln.startswith(prefix) else ln for ln in out.splitlines()]
    return {"matches": lines[:500], "truncated": len(lines) > 500}


# ── exec ────────────────────────────────────────────────────────────────────

@app.post("/exec")
async def exec_command(request: Request):
    body = await request.json()
    command = (body.get("command") or "").strip()
    if not command:
        raise HTTPException(400, "command required")
    cwd = _safe(body.get("cwd") or "")
    timeout = max(1, min(int(body.get("timeout") or 120), EXEC_MAX_TIMEOUT))
    started = time.monotonic()
    proc = await asyncio.create_subprocess_exec(
        "bash", "-lc", command, cwd=str(cwd), env=_child_env(),
        stdin=asyncio.subprocess.DEVNULL,
        stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE,
        start_new_session=True,
    )
    timed_out = False
    try:
        out, err = await asyncio.wait_for(proc.communicate(), timeout=timeout)
    except asyncio.TimeoutError:
        timed_out = True
        _kill_group(proc, signal.SIGKILL)
        out, err = await proc.communicate()
    return {
        "exit_code": proc.returncode,
        "stdout": _head_tail(out.decode(errors="replace")),
        "stderr": _head_tail(err.decode(errors="replace")),
        "timed_out": timed_out,
        "duration_ms": int((time.monotonic() - started) * 1000),
    }


# ── jobs (dev servers, installs, long builds) ───────────────────────────────

class Job:
    def __init__(self, name: str, command: str, cwd: Path):
        self.id = uuid.uuid4().hex[:10]
        self.name = name or command[:40]
        self.command = command
        self.cwd = cwd
        self.log_path = JOBS_DIR / f"{self.id}.log"
        self.started_at = int(time.time())
        log = open(self.log_path, "wb")
        self.proc = subprocess.Popen(
            ["bash", "-lc", command], cwd=str(cwd), env=_child_env(),
            stdin=subprocess.DEVNULL, stdout=log, stderr=subprocess.STDOUT,
            start_new_session=True,
        )
        log.close()

    def info(self) -> dict:
        code = self.proc.poll()
        return {
            "id": self.id, "name": self.name, "command": self.command, "cwd": _rel(self.cwd),
            "running": code is None, "exit_code": code, "started_at": self.started_at,
        }


JOBS: dict[str, Job] = {}


@app.post("/jobs")
async def job_start(request: Request):
    body = await request.json()
    command = (body.get("command") or "").strip()
    if not command:
        raise HTTPException(400, "command required")
    job = Job(body.get("name") or "", command, _safe(body.get("cwd") or ""))
    JOBS[job.id] = job
    return job.info()


@app.get("/jobs")
def job_list():
    return {"jobs": [j.info() for j in sorted(JOBS.values(), key=lambda j: -j.started_at)]}


@app.get("/jobs/{job_id}")
def job_get(job_id: str, offset: int = 0, limit: int = 60_000):
    job = JOBS.get(job_id)
    if not job:
        raise HTTPException(404, "no such job")
    size = job.log_path.stat().st_size if job.log_path.exists() else 0
    if offset < 0:  # negative → tail
        offset = max(0, size + offset)
    with open(job.log_path, "rb") as fh:
        fh.seek(min(offset, size))
        chunk = fh.read(max(1, min(limit, 200_000)))
    info = job.info()
    info.update(output=chunk.decode(errors="replace"), offset=offset,
                next_offset=offset + len(chunk), size=size)
    return info


@app.post("/jobs/{job_id}/stop")
def job_stop(job_id: str):
    job = JOBS.get(job_id)
    if not job:
        raise HTTPException(404, "no such job")
    if job.proc.poll() is None:
        _kill_group(job.proc)
        try:
            job.proc.wait(timeout=5)
        except subprocess.TimeoutExpired:
            _kill_group(job.proc, signal.SIGKILL)
    return job.info()


# ── previews ────────────────────────────────────────────────────────────────

@app.get("/ports")
def listening_ports():
    ports: set[int] = set()
    for table in ("/proc/net/tcp", "/proc/net/tcp6"):
        try:
            rows = Path(table).read_text().splitlines()[1:]
        except OSError:
            continue
        for row in rows:
            cols = row.split()
            if len(cols) > 3 and cols[3] == "0A":  # LISTEN
                ports.add(int(cols[1].rsplit(":", 1)[1], 16))
    ports.discard(7777)
    return {"ports": sorted(ports)}


_HOP = {"connection", "keep-alive", "proxy-authenticate", "proxy-authorization", "te",
        "trailers", "transfer-encoding", "upgrade", "host", "authorization", "content-length",
        "content-encoding"}


@app.api_route("/proxy/{port}/{path:path}",
               methods=["GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS"])
async def proxy(port: int, path: str, request: Request):
    if not (1 <= port <= 65535) or port == 7777:
        raise HTTPException(400, "bad port")
    params = [(k, v) for k, v in request.query_params.multi_items() if k != "token"]
    headers = {k: v for k, v in request.headers.items() if k.lower() not in _HOP}
    async with httpx.AsyncClient(timeout=60, follow_redirects=False) as client:
        try:
            upstream = await client.request(
                request.method, f"http://127.0.0.1:{port}/{path}", params=params,
                headers=headers, content=await request.body())
        except httpx.ConnectError:
            raise HTTPException(502, f"nothing is listening on port {port}")
    response = Response(upstream.content, status_code=upstream.status_code)
    # multi_items keeps repeated headers (several Set-Cookie) that a dict would merge.
    response.raw_headers.extend(
        (k.lower().encode("latin-1"), v.encode("latin-1"))
        for k, v in upstream.headers.multi_items() if k.lower() not in _HOP)
    return response


# ── terminal ────────────────────────────────────────────────────────────────

@app.websocket("/pty")
async def pty_socket(ws: WebSocket):
    raw = _bearer(ws.headers.get("authorization")) or ws.query_params.get("token")
    if not _token_ok(raw):
        await ws.close(code=4401)
        return
    await ws.accept()

    q = ws.query_params
    cols = int(q.get("cols") or 80)
    rows = int(q.get("rows") or 24)
    session = "".join(c for c in (q.get("session") or "main") if c.isalnum() or c in "-_")[:40] or "main"
    cwd = _safe(q.get("cwd") or "")
    startup = q.get("cmd") or ""

    master, slave = os.openpty()
    _set_size(master, cols, rows)

    def _ctty():
        fcntl.ioctl(0, termios.TIOCSCTTY, 0)

    # tmux keeps the shell (and anything like `claude` running in it) alive when
    # the phone drops the socket; reconnecting with the same session re-attaches.
    argv = ["tmux", "new-session", "-A", "-s", session, "-c", str(cwd)]
    if startup:
        argv += ["bash", "-lc", f"{startup}; exec bash -l"]
    proc = subprocess.Popen(
        argv, stdin=slave, stdout=slave, stderr=slave, cwd=str(cwd), env=_child_env(),
        start_new_session=True, preexec_fn=_ctty, close_fds=True,
    )
    os.close(slave)

    loop = asyncio.get_running_loop()
    queue: asyncio.Queue[bytes | None] = asyncio.Queue()

    def _readable():
        try:
            data = os.read(master, 65536)
        except OSError:
            data = b""
        if data:
            queue.put_nowait(data)
        else:
            loop.remove_reader(master)
            queue.put_nowait(None)

    loop.add_reader(master, _readable)

    async def pump_out():
        while True:
            data = await queue.get()
            if data is None:
                break
            await ws.send_bytes(data)
        await ws.close()

    sender = asyncio.create_task(pump_out())
    try:
        while True:
            msg = await ws.receive()
            if msg["type"] == "websocket.disconnect":
                break
            text = msg.get("text")
            if text is None and msg.get("bytes") is not None:
                os.write(master, msg["bytes"])
                continue
            try:
                frame = json.loads(text or "{}")
            except json.JSONDecodeError:
                continue
            if frame.get("type") == "input":
                os.write(master, (frame.get("data") or "").encode())
            elif frame.get("type") == "resize":
                _set_size(master, int(frame.get("cols") or cols), int(frame.get("rows") or rows))
    except (WebSocketDisconnect, RuntimeError):
        pass
    finally:
        sender.cancel()
        try:
            loop.remove_reader(master)
        except (ValueError, OSError):
            pass
        # Detach only: killing the tmux *client* leaves the session running.
        if proc.poll() is None:
            proc.terminate()
        os.close(master)


def _set_size(fd: int, cols: int, rows: int) -> None:
    fcntl.ioctl(fd, termios.TIOCSWINSZ, struct.pack("HHHH", max(1, rows), max(1, cols), 0, 0))
