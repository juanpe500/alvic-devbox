# ── auth ────────────────────────────────────────────────────────────────────

def _token_ok(raw: str | None) -> bool:
    return bool(TOKEN) and bool(raw) and hmac.compare_digest(raw, TOKEN)


def _bearer(value: str | None) -> str | None:
    if value and value.lower().startswith("bearer "):
        return value[7:].strip()
    return None


@app.middleware("http")
async def require_token(request: Request, call_next):
    raw = _bearer(request.headers.get("authorization")) or request.query_params.get("token")
    if not _token_ok(raw):
        return JSONResponse({"error": "unauthorized"}, status_code=401)
    return await call_next(request)


# ── helpers ─────────────────────────────────────────────────────────────────

def _safe(path: str | None) -> Path:
    """Resolve a path (relative to $HOME, or absolute inside it). Never escapes $HOME."""
    raw = (path or "").strip()
    target = Path(raw) if raw.startswith("/") else HOME / raw
    target = target.resolve()
    if target != HOME and HOME not in target.parents:
        raise HTTPException(400, "path escapes the home folder")
    return target


def _rel(p: Path) -> str:
    return "" if p == HOME else str(p.relative_to(HOME))


def _head_tail(text: str, limit: int = OUTPUT_MAX) -> str:
    if len(text) <= limit:
        return text
    head, tail = text[: int(limit * 0.6)], text[-int(limit * 0.4):]
    return f"{head}\n\n… [{len(text) - len(head) - len(tail):,} chars omitted] …\n\n{tail}"


def _child_env(extra: dict | None = None) -> dict:
    env = {k: v for k, v in os.environ.items() if k != "AGENT_TOKEN"}
    env.setdefault("TERM", "xterm-256color")
    env["HOME"] = str(HOME)
    if extra:
        env.update(extra)
    return env


def _kill_group(proc: subprocess.Popen | asyncio.subprocess.Process, sig=signal.SIGTERM) -> None:
    try:
        os.killpg(proc.pid, sig)
    except (ProcessLookupError, PermissionError):
        pass


